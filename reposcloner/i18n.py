def get_lang(config=None) -> str:
    """Resolve UI language from config; Russian unless explicitly 'en'."""
    lang = (config or {}).get('language', DEFAULT_LANGUAGE)
    return lang if lang in STRINGS else DEFAULT_LANGUAGE


def t(key: str, lang: str = DEFAULT_LANGUAGE, **kwargs) -> str:
    """Translate *key*; falls back to Russian (primary), then to the key itself."""
    template = STRINGS.get(lang, {}).get(key, STRINGS['ru'].get(key, key))
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template
